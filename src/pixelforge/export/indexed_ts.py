"""Direct `--indexed-ts` Uint8Array + palette/manifest TypeScript exporter."""

from __future__ import annotations

import base64
import json
from collections.abc import Sequence
from dataclasses import dataclass
from pathlib import Path

import numpy as np
from numpy.typing import NDArray

from pixelforge.core.palette import resolve_reflections
from pixelforge.core.types import TRANSPARENT_INDEX, StylePack
from pixelforge.export.bundle import ExportBundleResult


@dataclass(frozen=True)
class IndexedTsExportResult:
    """Generated TypeScript sources for CPU indexed framebuffer targets."""

    palette_ts: str
    sprites_ts: str
    manifest_ts: str


def encode_rle_bytes(data: NDArray[np.uint8]) -> bytes:
    """Compress a 1D/2D uint8 array using `[run_len - 1, value]` byte pairs (max run 256)."""
    flat = np.ascontiguousarray(data, dtype=np.uint8).ravel()
    total = int(flat.size)
    if total == 0:
        return b""

    # INVARIANT: Run lengths are encoded as `(count - 1) in 0..255` so runs up to 256
    # pack into 2 bytes without a variable-length header, keeping the TS decoder trivial.
    out = bytearray()
    raw = flat.tolist()
    idx = 0
    while idx < total:
        val = raw[idx]
        run = 1
        while idx + run < total and run < 256 and raw[idx + run] == val:
            run += 1
        out.append(run - 1)
        out.append(val)
        idx += run
    return bytes(out)


def decode_rle_bytes(encoded: bytes, expected_len: int) -> NDArray[np.uint8]:
    """Decode `[run_len - 1, value]` RLE bytes back into a flat uint8 array."""
    if len(encoded) % 2 != 0:
        msg = f"Invalid RLE byte stream length {len(encoded)} (must be even)"
        raise ValueError(msg)
    out = bytearray()
    for i in range(0, len(encoded), 2):
        count = encoded[i] + 1
        value = encoded[i + 1]
        out.extend([value] * count)
    if len(out) != expected_len:
        msg = f"RLE decoded length {len(out)} does not match expected {expected_len}"
        raise ValueError(msg)
    return np.frombuffer(bytes(out), dtype=np.uint8).copy()


def generate_palette_ts(style: StylePack) -> str:
    """Generate `palette.generated.ts` exporting `PALETTE_HEX`, `EMISSIVE`, `BRIGHT`, `REFL`."""
    max_idx = max(entry.index for entry in style.palette)
    hex_table = ["#000000"] * (max_idx + 1)
    emissive_indices: list[int] = []
    bright_indices: list[int] = []

    for entry in sorted(style.palette, key=lambda item: item.index):
        hex_table[entry.index] = entry.hex
        if "emissive" in entry.flags:
            emissive_indices.append(entry.index)
        if "bright" in entry.flags:
            bright_indices.append(entry.index)

    refl_map = resolve_reflections(style)
    refl_entries = ", ".join(f"{src}: {dst}" for src, dst in sorted(refl_map.items()))
    hex_entries = ", ".join(json.dumps(h) for h in hex_table)
    emissive_list = ", ".join(str(i) for i in emissive_indices)
    bright_list = ", ".join(str(i) for i in bright_indices)

    lines = [
        "// Auto-generated by pixelforge --indexed-ts — do not edit manually.",
        "",
        f"export const STYLE_ID = {json.dumps(style.id)} as const;",
        f"export const TRANSPARENT_INDEX = {TRANSPARENT_INDEX} as const;",
        f"export const OUTLINE_INDEX = {style.outline_index} as const;",
        "",
        f"export const PALETTE_HEX: readonly string[] = [{hex_entries}] as const;",
        "",
        f"export const EMISSIVE: ReadonlySet<number> = new Set<number>([{emissive_list}]);",
        f"export const BRIGHT: ReadonlySet<number> = new Set<number>([{bright_list}]);",
        "",
        f"export const REFL: Readonly<Record<number, number>> = {{{refl_entries}}} as const;",
        "",
    ]
    return "\n".join(lines)


def _decode_rle_ts_helper() -> list[str]:
    return [
        "const _B64_REV = new Int16Array(128).fill(-1);",
        "const _B64_ALPHA = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';",
        "for (let i = 0; i < _B64_ALPHA.length; i++) {",
        "  _B64_REV[_B64_ALPHA.charCodeAt(i)] = i;",
        "}",
        "",
        "function decodeBase64Bytes(b64: string): Uint8Array {",
        "  const clean = b64.replace(/=+$/, '');",
        "  const byteLen = (clean.length * 3) >> 2;",
        "  const out = new Uint8Array(byteLen);",
        "  let p = 0;",
        "  for (let i = 0; i < clean.length; i += 4) {",
        "    const a = _B64_REV[clean.charCodeAt(i)] ?? 0;",
        "    const b = _B64_REV[clean.charCodeAt(i + 1)] ?? 0;",
        "    const c = i + 2 < clean.length ? (_B64_REV[clean.charCodeAt(i + 2)] ?? 0) : 0;",
        "    const d = i + 3 < clean.length ? (_B64_REV[clean.charCodeAt(i + 3)] ?? 0) : 0;",
        "    const triple = (a << 18) | (b << 12) | (c << 6) | d;",
        "    if (p < byteLen) out[p++] = (triple >> 16) & 0xff;",
        "    if (p < byteLen) out[p++] = (triple >> 8) & 0xff;",
        "    if (p < byteLen) out[p++] = triple & 0xff;",
        "  }",
        "  return out;",
        "}",
        "",
        "export function decodeRleSprite(b64: string, width: number, height: number): Uint8Array {",
        "  const packed = decodeBase64Bytes(b64);",
        "  const out = new Uint8Array(width * height);",
        "  let cursor = 0;",
        "  for (let i = 0; i < packed.length; i += 2) {",
        "    const count = (packed[i] ?? 0) + 1;",
        "    const value = packed[i + 1] ?? 255;",
        "    out.fill(value, cursor, cursor + count);",
        "    cursor += count;",
        "  }",
        "  return out;",
        "}",
    ]


def _lazy_sprite_ts_helper() -> list[str]:
    return [
        "function createLazySpriteFrame(",
        "  b64: string,",
        "  width: number,",
        "  height: number,",
        "): IndexedSpriteFrame {",
        "  let cached: Uint8Array | undefined;",
        "  return {",
        "    width,",
        "    height,",
        "    get data(): Uint8Array {",
        "      if (cached === undefined) {",
        "        cached = decodeRleSprite(b64, width, height);",
        "      }",
        "      return cached;",
        "    },",
        "  };",
        "}",
    ]


def generate_sprites_ts(
    bundles: Sequence[ExportBundleResult],
    *,
    lazy: bool = False,
) -> str:
    """Generate `sprites.generated.ts` containing RLE-base64 `Uint8Array` index buffers."""
    ordered = sorted(bundles, key=lambda b: b.manifest.id)
    lines: list[str] = [
        "// Auto-generated by pixelforge --indexed-ts — do not edit manually.",
        "",
        "export interface IndexedSpriteFrame {",
        "  readonly width: number;",
        "  readonly height: number;",
        "  readonly data: Uint8Array;",
        "}",
        "",
        *_decode_rle_ts_helper(),
    ]
    if lazy:
        lines.extend(["", *_lazy_sprite_ts_helper()])
    lines.extend(["", "export const INDEXED_SPRITES = {"])

    for bundle in ordered:
        m = bundle.manifest
        by_key = {(f.state, f.frame): f for f in bundle.rendered_frames}
        lines.append(f"  {json.dumps(m.id)}: {{")
        for state in m.states:
            lines.append(f"    {json.dumps(state)}: [")
            for frame_idx in range(m.frames):
                rendered = by_key[(state, frame_idx)]
                rle_b64 = base64.b64encode(encode_rle_bytes(rendered.surface.data)).decode("ascii")
                if lazy:
                    encoded_b64 = json.dumps(rle_b64)
                    lines.append(
                        f"      createLazySpriteFrame({encoded_b64}, {m.width}, {m.height}),"
                    )
                else:
                    lines.append(
                        "      { "
                        f"width: {m.width}, "
                        f"height: {m.height}, "
                        f"data: decodeRleSprite({json.dumps(rle_b64)}, {m.width}, {m.height}) "
                        "},"
                    )
            lines.append("    ],")
        lines.append("  },")

    lines.extend(
        [
            "} as const;",
            "",
            "export type IndexedSpriteAssetId = keyof typeof INDEXED_SPRITES;",
            "",
            "export function getIndexedSpriteFrame<K extends IndexedSpriteAssetId>(",
            "  id: K,",
            "  state: keyof (typeof INDEXED_SPRITES)[K],",
            "  frame = 0,",
            "): IndexedSpriteFrame {",
            "  const frames = INDEXED_SPRITES[id][state] as readonly IndexedSpriteFrame[];",
            "  return frames[frame % frames.length] as IndexedSpriteFrame;",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def generate_indexed_manifest_ts(bundles: Sequence[ExportBundleResult]) -> str:
    """Generate `manifest.generated.ts` with typed metadata for CPU indexed framebuffers."""
    ordered = sorted(bundles, key=lambda b: b.manifest.id)
    manifest_payload = {
        bundle.manifest.id: {
            "id": bundle.manifest.id,
            "styleId": bundle.manifest.styleId,
            "perspective": bundle.manifest.perspective,
            "width": bundle.manifest.width,
            "height": bundle.manifest.height,
            "states": list(bundle.manifest.states),
            "frames": bundle.manifest.frames,
            "fps": bundle.manifest.fps,
            "anchors": [
                a.model_dump(exclude_none=True, mode="json") for a in bundle.manifest.anchors
            ],
            "hitboxes": [
                h.model_dump(exclude_none=True, mode="json") for h in bundle.manifest.hitboxes
            ],
            **(
                {"nineSlice": bundle.manifest.nineSlice.model_dump(mode="json")}
                if bundle.manifest.nineSlice is not None
                else {}
            ),
            **(
                {"tilemap": bundle.manifest.tilemap.model_dump(mode="json")}
                if bundle.manifest.tilemap is not None
                else {}
            ),
            **(
                {"semantics": bundle.manifest.semantics.model_dump(mode="json")}
                if bundle.manifest.semantics is not None
                else {}
            ),
            **(
                {
                    "frameMetadata": {
                        st: [entry.model_dump(exclude_none=True, mode="json") for entry in entries]
                        for st, entries in bundle.manifest.frameMetadata.items()
                    }
                }
                if bundle.manifest.frameMetadata is not None
                else {}
            ),
            "sha256": bundle.manifest.sha256,
        }
        for bundle in ordered
    }
    encoded = json.dumps(manifest_payload, indent=2)
    lines = [
        "// Auto-generated by pixelforge --indexed-ts — do not edit manually.",
        "",
        f"export const INDEXED_MANIFEST = {encoded} as const;",
        "",
        "export type IndexedAssetId = keyof typeof INDEXED_MANIFEST;",
        "export type IndexedAssetManifestEntry<K extends IndexedAssetId = IndexedAssetId> =",
        "  (typeof INDEXED_MANIFEST)[K];",
        "",
    ]
    return "\n".join(lines)


def export_indexed_ts(
    bundles: Sequence[ExportBundleResult],
    style: StylePack,
    *,
    lazy: bool = False,
) -> IndexedTsExportResult:
    """Compile asset bundles and `StylePack` into self-contained TS indexed framebuffer modules."""
    for bundle in bundles:
        if bundle.manifest.styleId != style.id:
            msg = (
                f"Asset {bundle.manifest.id!r} targets style {bundle.manifest.styleId!r}, "
                f"expected {style.id!r}"
            )
            raise ValueError(msg)

    return IndexedTsExportResult(
        palette_ts=generate_palette_ts(style),
        sprites_ts=generate_sprites_ts(bundles, lazy=lazy),
        manifest_ts=generate_indexed_manifest_ts(bundles),
    )


def write_indexed_ts_bundle(
    result: IndexedTsExportResult,
    out_dir: Path,
) -> tuple[Path, Path, Path]:
    """Write `palette.generated.ts`, `sprites.generated.ts`, and `manifest.generated.ts`."""
    out_dir.mkdir(parents=True, exist_ok=True)
    palette_path = out_dir / "palette.generated.ts"
    sprites_path = out_dir / "sprites.generated.ts"
    manifest_path = out_dir / "manifest.generated.ts"

    palette_path.write_text(result.palette_ts, encoding="utf-8")
    sprites_path.write_text(result.sprites_ts, encoding="utf-8")
    manifest_path.write_text(result.manifest_ts, encoding="utf-8")
    return (palette_path, sprites_path, manifest_path)
